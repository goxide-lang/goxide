func TestNativeImportKeepsIndependentNestedModuleIdentity(t *testing.T) {
	for _, source := range []string{"pure_go", "goxide_library"} {
		t.Run(source, func(t *testing.T) {
			base := t.TempDir()
			root, dependency := filepath.Join(base, "app"), filepath.Join(base, "codec")
			const module = "review.example/nested/codec"
			if source == "pure_go" {
				writeProjectFile(t, dependency, "go.mod", "module "+module+"\ngo 1.27\n")
				writeProjectFile(t, dependency, "codec.go", "package codec\ntype Token struct { Value int }\nfunc Make() Token { return Token{Value: 42} }\n")
			} else {
				writeProjectFile(t, dependency, project.ManifestName, "[go_mod]\nmodule='"+module+"'\ngo='1.27'\n[lib]\nname='library_name'\npath='.'\n")
				writeProjectFile(t, dependency, "codec.gox", "package codec\ntype Token struct { Value int }\nfunc Make() Token { return Token{Value: 42} }\n")
			}
			writeProjectFile(t, root, project.ManifestName, `[go_mod]
module = "review.example/nested"
go = "1.27"
[[bin]]
name = "app"
path = "src"
[dependencies.codec]
path = "../codec"
`)
			const native = `package main
import "review.example/nested/codec"
func nativeToken() codec.Token { return codec.Make() }
`
			writeProjectFile(t, root, "src/native.go", native)
			writeProjectFile(t, root, "src/main.gox", `package main
use codec;
use fmt;
func main() {
	var value codec::Token = nativeToken()
	fmt::Println(value.Value, codec::Make().Value)
}
`)
			first, err := PrepareProject(root, Options{Offline: true})
			if err != nil {
				t.Fatal(err)
			}
			if got := featureGo(t, first.Root, "run", first.Entry); got != "42 42\n" {
				t.Fatalf("independent module returned %q", got)
			}
			generated, err := os.ReadFile(filepath.Join(first.Root, "src/main.go"))
			if err != nil || !strings.Contains(string(generated), `"`+module+`"`) {
				t.Fatalf("generated import lost module identity: %v\n%s", err, generated)
			}
			copied, err := os.ReadFile(filepath.Join(first.Root, "src/native.go"))
			if err != nil || string(copied) != native {
				t.Fatalf("native source changed: %v\n%s", err, copied)
			}
			files := projectSnapshot(t, filepath.Dir(first.Root))
			lock, err := os.ReadFile(filepath.Join(root, "goxide.lock"))
			if err != nil {
				t.Fatal(err)
			}
			second, err := PrepareProject(root, Options{Offline: true, Locked: true})
			if err != nil {
				t.Fatal(err)
			}
			after, err := os.ReadFile(filepath.Join(root, "goxide.lock"))
			if err != nil || !bytes.Equal(lock, after) || first.Root != second.Root || !reflect.DeepEqual(files, projectSnapshot(t, filepath.Dir(second.Root))) {
				t.Fatalf("locked source replay changed generated bytes or lock: %v", err)
			}
		})
	}
}

func TestNativeLibraryImportDoesNotEnterBinWithModulePrefix(t *testing.T) {
	base := t.TempDir()
	root, dependency := filepath.Join(base, "app"), filepath.Join(base, "codec")
	writeProjectFile(t, dependency, "go.mod", "module review.example/nested/cmd/app/codec\ngo 1.27\n")
	writeProjectFile(t, dependency, "codec.go", "package codec\nfunc Value() int { return 42 }\n")
	writeProjectFile(t, root, project.ManifestName, `[go_mod]
module = "review.example/nested"
go = "1.27"
[lib]
name = "core"
path = "src"
[[bin]]
name = "app"
path = "cmd/app"
[dependencies.codec]
path = "../codec"
`)
	writeProjectFile(t, root, "src/lib.gox", "package core\nfunc Value() int { return nativeValue() }\n")
	writeProjectFile(t, root, "src/native.go", `package core
import "review.example/nested/cmd/app/codec"
func nativeValue() int { return codec.Value() }
`)
	writeProjectFile(t, root, "cmd/app/main.gox", "package main\nuse core;\nuse fmt;\nfunc main() { fmt::Println(core::Value()) }\n")
	result, err := PrepareProject(root, Options{Offline: true})
	if err != nil {
		t.Fatal(err)
	}
	if got := featureGo(t, result.Root, "run", result.Entry); got != "42\n" {
		t.Fatalf("independent module under binary path returned %q", got)
	}
}

func TestNativeImportRecognizesNestedModuleSelectedByGoConfig(t *testing.T) {
	base := t.TempDir()
	root, dependency := filepath.Join(base, "app"), filepath.Join(base, "codec")
	writeProjectFile(t, dependency, "go.mod", "module review.example/nested/codec\ngo 1.27\n")
	writeProjectFile(t, dependency, "codec.go", "package codec\nfunc Value() int { return 42 }\n")
	writeProjectFile(t, root, project.ManifestName, `[go_mod]
module = "review.example/nested"
go = "1.27"
[[bin]]
name = "app"
path = "src"
[go]
require = [{ module = "review.example/nested/codec", version = "v0.0.0" }]
replace = [{ module = "review.example/nested/codec", path = "../codec" }]
`)
	writeProjectFile(t, root, "src/native.go", `package main
import "review.example/nested/codec"
func nativeValue() int { return codec.Value() }
`)
	writeProjectFile(t, root, "src/main.gox", "package main\nuse fmt;\nfunc main() { fmt::Println(nativeValue()) }\n")
	result, err := PrepareProject(root, Options{Offline: true})
	if err != nil {
		t.Fatal(err)
	}
	if got := featureGo(t, result.Root, "run", result.Entry); got != "42\n" {
		t.Fatalf("native selected module returned %q", got)
	}
}
