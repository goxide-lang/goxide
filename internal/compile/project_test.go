func TestBinaryFileTargetRetainsResourcesAndStableBytes(t *testing.T) {
	root := smallProject(t)
	writeProjectFile(t, root, "other.gox", "not valid source")
	writeProjectFile(t, root, "assets/native.go", "package assets\nimport _ \"embed\"\n//go:embed testdata/payload.gox\nvar Payload string\n")
	writeProjectFile(t, root, "assets/testdata/payload.gox", "this is resource data, not source")
	manifest, err := os.OpenFile(filepath.Join(root, project.ManifestName), os.O_APPEND|os.O_WRONLY, 0o600)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := manifest.WriteString("\n[[bin]]\nname='other'\npath='other.gox'\n"); err != nil {
		t.Fatal(err)
	}
	if err := manifest.Close(); err != nil {
		t.Fatal(err)
	}
	first, err := PrepareProject(root, Options{Bin: "app", Offline: true})
	if err != nil {
		t.Fatal(err)
	}
	if first.Entry != "./goxide_targets/bin/app" {
		t.Fatalf("file target package = %q", first.Entry)
	}
	command := exec.Command(filepath.Join(runtime.GOROOT(), "bin", "go"), "run", "-mod=readonly", first.Entry)
	command.Dir, command.Env = first.Root, project.GoEnv(true)
	if output, err := command.CombinedOutput(); err != nil || string(output) != "file target\n" {
		t.Fatalf("generated file target: %v\n%s", err, output)
	}
	firstFiles := projectSnapshot(t, filepath.Dir(first.Root))
	if string(firstFiles["module/assets/testdata/payload.gox"]) != "this is resource data, not source" {
		t.Fatal("native embed resource was changed")
	}
	if _, exists := firstFiles["module/other.gox"]; exists {
		t.Fatal("unselected binary source was staged")
	}
	second, err := PrepareProject(root, Options{Bin: "app", Offline: true, Locked: true})
	if err != nil {
		t.Fatal(err)
	}
	if first.Root != second.Root || !reflect.DeepEqual(firstFiles, projectSnapshot(t, filepath.Dir(second.Root))) {
		t.Fatal("unchanged file target changed its path or generated bytes")
	}
}

func TestFailedGenerationPreservesPublishedProject(t *testing.T) {
	root := smallProject(t)
	first, err := PrepareProject(root, Options{Offline: true})
	if err != nil {
		t.Fatal(err)
	}
	files := projectSnapshot(t, filepath.Dir(first.Root))
	lock, err := os.ReadFile(filepath.Join(root, "goxide.lock"))
	if err != nil {
		t.Fatal(err)
	}
	writeProjectFile(t, root, "app.gox", "package main\nfunc main( {\n")
	if _, err := PrepareProject(root, Options{Offline: true, Locked: true}); err == nil {
		t.Fatal("invalid source succeeded")
	}
	after, err := os.ReadFile(filepath.Join(root, "goxide.lock"))
	if err != nil || !bytes.Equal(lock, after) || !reflect.DeepEqual(files, projectSnapshot(t, filepath.Dir(first.Root))) {
		t.Fatalf("failed lowering changed published source or lock: %v", err)
	}
}

func TestProjectRejectsDeferredCapabilities(t *testing.T) {
	for _, test := range []struct {
		name, extra, want string
	}{
		{"workspace", "\n[workspace]\nmembers=[]\n", "workspace"},
		{"build", "\n[build]\nentry='build.gox'\ninputs=['build.gox']\noutputs=['generated.go']\n", "build"},
		{"example", "\n[[example]]\nname='demo'\npath='app.gox'\n", "example"},
	} {
		t.Run(test.name, func(t *testing.T) {
			root := smallProject(t)
			name := filepath.Join(root, project.ManifestName)
			contents, err := os.ReadFile(name)
			if err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(name, append(contents, test.extra...), 0o600); err != nil {
				t.Fatal(err)
			}
			if _, err := PrepareProject(root, Options{Offline: true}); err == nil || !strings.Contains(err.Error(), test.want) {
				t.Fatalf("deferred %s diagnostic: %v", test.name, err)
			}
			if _, err := os.Stat(filepath.Join(root, "goxide.lock")); !os.IsNotExist(err) {
				t.Fatalf("deferred capability published a lock: %v", err)
			}
		})
	}
}

func TestChangingTargetDirectoryKeepsLock(t *testing.T) {
	root := smallProject(t)
	first, err := PrepareProject(root, Options{Offline: true})
	if err != nil {
		t.Fatal(err)
	}
	lock, err := os.ReadFile(filepath.Join(root, "goxide.lock"))
	if err != nil {
		t.Fatal(err)
	}
	second, err := PrepareProject(root, Options{TargetDir: "other-output", Offline: true, Locked: true})
	if err != nil {
		t.Fatal(err)
	}
	if first.Root == second.Root {
		t.Fatal("target directory was ignored")
	}
	after, err := os.ReadFile(filepath.Join(root, "goxide.lock"))
	if err != nil || !bytes.Equal(lock, after) {
		t.Fatalf("target directory changed lock: %v", err)
	}
}

func TestOrdinaryTargetDirectoryIsSource(t *testing.T) {
	root := smallProject(t)
	name := filepath.Join(root, project.ManifestName)
	manifest, err := os.ReadFile(name)
	if err != nil {
		t.Fatal(err)
	}
	manifest = append(manifest, "\n[namespaces]\nhelper='example.org/small/target'\n"...)
	if err := os.WriteFile(name, manifest, 0o600); err != nil {
		t.Fatal(err)
	}
	writeProjectFile(t, root, "target/value.gox", "package helper\nfunc Value() string { return \"ordinary target\" }\n")
	writeProjectFile(t, root, "app.gox", "package main\nuse fmt;\nuse helper;\nfunc main() { fmt::Println(helper::Value()) }\n")
	result, err := PrepareProject(root, Options{Offline: true, TargetDir: "build-output"})
	if err != nil {
		t.Fatal(err)
	}
	command := exec.Command(filepath.Join(runtime.GOROOT(), "bin", "go"), "run", "-mod=readonly", result.Entry)
	command.Dir, command.Env = result.Root, project.GoEnv(true)
	if output, err := command.CombinedOutput(); err != nil || string(output) != "ordinary target\n" {
		t.Fatalf("ordinary target package: %v\n%s", err, output)
	}
}

func TestExternalTestPackageKeepsImportedIdentity(t *testing.T) {
	root := t.TempDir()
	writeProjectFile(t, root, project.ManifestName, `[go_mod]
module = "example.org/testpkg"
go = "1.27"
[namespaces]
lib = "example.org/testpkg/lib"
[[bin]]
name = "app"
path = "cmd/app"
[dependencies]
testing = { go = "testing" }
`)
	writeProjectFile(t, root, "cmd/app/main.gox", "package main\nuse lib;\nfunc main() { _ = lib::Value() }\n")
	writeProjectFile(t, root, "lib/api.gox", "package lib\ntype Number struct { Value int }\nfunc Value() int { return 42 }\n")
	writeProjectFile(t, root, "lib/api_test.gox", `package lib_test
use testing;
use lib;
func TestValue(t *testing::T) {
	var value lib::Number = lib::Number{Value: lib::Value()}
	if value.Value != 42 { t.Fatal("wrong value") }
}
`)
	result, err := PrepareProject(root, Options{Offline: true})
	if err != nil {
		t.Fatal(err)
	}
	command := exec.Command(filepath.Join(runtime.GOROOT(), "bin", "go"), "test", "-mod=readonly", "-count=1", "./...")
	command.Dir, command.Env = result.Root, project.GoEnv(true)
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("generated external test package: %v\n%s", err, output)
	}
}

func smallProject(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	writeProjectFile(t, root, project.ManifestName, "[go_mod]\nmodule='example.org/small'\ngo='1.27'\n[[bin]]\nname='app'\npath='app.gox'\n[dependencies]\nfmt={go='fmt'}\n")
	writeProjectFile(t, root, "app.gox", "package main\nuse fmt;\nfunc main() { fmt::Println(\"file target\") }\n")
	return root
}

func writeProjectFile(t *testing.T, root, name, contents string) {
	t.Helper()
	filename := filepath.Join(root, name)
	if err := os.MkdirAll(filepath.Dir(filename), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filename, []byte(contents), 0o600); err != nil {
		t.Fatal(err)
	}
}

func projectSnapshot(t *testing.T, root string) map[string][]byte {
	t.Helper()
	files := map[string][]byte{}
	err := filepath.WalkDir(root, func(name string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}
		relative, err := filepath.Rel(root, name)
		if err != nil {
			return err
		}
		data, err := os.ReadFile(name)
		if err == nil {
			files[filepath.ToSlash(relative)] = data
		}
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	return files
}
