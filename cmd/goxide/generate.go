const generatedHeader = "// Code generated by goxide. DO NOT EDIT.\n\n"

// generatePackage reads the selected package in place; only its generated Go
// files are published. Module queries use a private copy of go.mod and go.sum.
func generatePackage(req CompileRequest, out io.Writer) error {
	if req.NoDefaultFeatures {
		return fmt.Errorf("--no-default-features requires goxide.toml")
	}
	if req.Bin != "" || req.Example != "" || req.Lib || req.TargetDir != "" || req.Offline || req.Locked {
		return fmt.Errorf("project selection flags require build/run/test or transpile -o DIRECTORY")
	}
	if req.Expanded != "" {
		return fmt.Errorf("--expanded requires single-file transpile -o FILE")
	}
	input, err := filepath.Abs(req.Input)
	if err != nil {
		return err
	}
	input, err = filepath.EvalSymlinks(input)
	if err != nil {
		return err
	}
	info, err := os.Stat(input)
	if err != nil {
		return err
	}
	directory, selected := input, ""
	if !info.IsDir() {
		if filepath.Ext(input) != ".gox" {
			return fmt.Errorf("gen requires a package directory or a .gox file")
		}
		if req.Tags != "" {
			return fmt.Errorf("--tags requires directory mode")
		}
		directory, selected = filepath.Dir(input), input
	}
	if selected != "" && req.Output != "-" && (req.FeaturesSet || req.Features != "") {
		return fmt.Errorf("feature configuration requires whole-package generation; use gen with a directory input")
	}
	entries, err := os.ReadDir(directory)
	if err != nil {
		return err
	}
	files := map[string][]byte{}
	var sources []string
	buildContext := req.config.Environment.Context(strings.FieldsFunc(req.Tags, func(r rune) bool { return r == ',' || r == ' ' }), false)
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || strings.HasSuffix(name, "_test.go") || strings.HasSuffix(name, "_test.gox") {
			continue
		}
		ext := filepath.Ext(name)
		if ext != ".go" && ext != ".gox" {
			continue
		}
		filename := filepath.Join(directory, name)
		if ext == ".gox" && selected != "" && filename != selected && req.Output == "-" {
			continue
		}
		data, err := os.ReadFile(filename)
		if err != nil {
			return err
		}
		if ext == ".go" && strings.HasSuffix(name, "_gox.go") && generatedGo(filename, data) {
			continue
		}
		matchName := strings.TrimSuffix(name, ext) + ".go"
		buildContext.OpenFile = func(string) (io.ReadCloser, error) {
			return io.NopCloser(strings.NewReader(string(data))), nil
		}
		matches, err := buildContext.MatchFile(directory, matchName)
		if err != nil {
			return err
		}
		if !matches && filename != selected {
			continue
		}
		if ext == ".go" && !buildContext.CgoEnabled {
			file, err := goparser.ParseFile(gotoken.NewFileSet(), filename, data, goparser.ImportsOnly|goparser.SkipObjectResolution)
			if err != nil {
				return err
			}
			cgo := false
			for _, imported := range file.Imports {
				name, _ := strconv.Unquote(imported.Path.Value)
				cgo = cgo || name == "C"
			}
			if cgo {
				continue
			}
		}
		if ext == ".gox" && selected != "" {
			if req.Output != "-" && sourceUsesConfiguration(data) {
				return fmt.Errorf("%s: conditional compilation requires whole-package generation; use gen with a directory input", filename)
			}
			if filename != selected {
				continue
			}
		}
		if err := naming.Source(filename, data); err != nil {
			return err
		}
		files[filename] = data
		if ext == ".gox" && (selected == "" || filename == selected) {
			sources = append(sources, filename)
		}
	}
	if len(sources) == 0 {
		return fmt.Errorf("%s: no .gox files in this package", directory)
	}
	if req.Output == "-" && len(sources) != 1 {
		return fmt.Errorf("-o - requires one .gox file; select a single file instead of this package")
	}
	for _, source := range sources {
		if req.Output != "-" {
			if err := checkGeneratedOutput(generatedFilename(source)); err != nil {
				return err
			}
		}
	}
	owner, err := prepareSingleFileModule(sources[0], req.config)
	if err != nil {
		return err
	}
	moduleRoot, packagePath, importSource, modFile := "", "goxide/generated", sources[0], ""
	if owner != nil {
		defer owner.close()
		moduleRoot, packagePath, modFile = owner.root, owner.packagePath, owner.modFile
	} else {
		temporary, err := os.MkdirTemp("", "goxide-gen-")
		if err != nil {
			return err
		}
		defer os.RemoveAll(temporary)
		modFile = filepath.Join(temporary, "go.mod")
		if err := os.WriteFile(modFile, []byte("module goxide/generated\n\ngo 1.27\n"), 0600); err != nil {
			return err
		}
		importSource = filepath.Join(temporary, "input.gox")
	}
	roots, err := sourceRoots(moduleRoot, directory, req.RootsFile)
	if err != nil {
		return err
	}
	imports := typecheck.NewImporter(importSource, typecheck.ImporterOptions{Config: req.config, Tags: buildContext.BuildTags, ModFile: modFile})
	generated, err := lower.CompilePackage(files, packagePath, imports, roots, lower.PackageOptions{LineDirectives: true, Config: req.config, RejectConfiguration: selected != "" && req.Output != "-"})
	if err != nil {
		return generationDependencyError(err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	targets := exec.CommandContext(ctx, req.config.Environment.GoTool, "tool", "dist", "list")
	targets.Env = singleFileEnvironment(req.config.Environment.ExecEnv())
	targetList, err := targets.Output()
	if err != nil {
		return fmt.Errorf("read Go platform names: %w", err)
	}
	operatingSystems, architectures := map[string]bool{}, map[string]bool{}
	for _, target := range strings.Fields(string(targetList)) {
		os, arch, ok := strings.Cut(target, "/")
		if ok {
			operatingSystems[os], architectures[arch] = true, true
		}
	}
	for _, source := range sources {
		generated[source], err = generatedBuildConstraint(source, generated[source], operatingSystems, architectures)
		if err != nil {
			return err
		}
		file, err := goparser.ParseFile(gotoken.NewFileSet(), source, generated[source], goparser.ImportsOnly|goparser.SkipObjectResolution)
		if err != nil {
			return err
		}
		for _, imported := range file.Imports {
			path, err := strconv.Unquote(imported.Path.Value)
			if err != nil {
				return err
			}
			if runtimeImport.MatchString(path) {
				if _, err := imports.Import(path); err != nil {
					return generationDependencyError(fmt.Errorf("generated Go requires %s: %w", path, err))
				}
			}
		}
	}
	if selected == "" {
		if err := checkGeneratedPackage(packagePath, files, generated, imports, req.config.Sizes()); err != nil {
			return generationDependencyError(err)
		}
	}
	if req.Output == "-" {
		_, err := out.Write(append([]byte(generatedHeader), generated[sources[0]]...))
		return err
	}
	// Prepare every file before replacing any output. Rename replaces a hard
	// link rather than writing through it into another source file.
	staged := map[string]string{}
	defer func() {
		for _, temporary := range staged {
			os.Remove(temporary)
		}
	}()
	for _, source := range sources {
		target := generatedFilename(source)
		file, err := os.CreateTemp(directory, ".goxide-gen-*")
		if err != nil {
			return err
		}
		staged[target] = file.Name()
		_, writeErr := file.Write(append([]byte(generatedHeader), generated[source]...))
		if err := file.Close(); writeErr == nil {
			writeErr = err
		}
		if writeErr != nil {
			return writeErr
		}
		if err := os.Chmod(file.Name(), 0644); err != nil {
			return err
		}
	}
	sort.Strings(sources)
	for _, source := range sources {
		target := generatedFilename(source)
		if err := checkGeneratedOutput(target); err != nil {
			return err
		}
		if err := os.Rename(staged[target], target); err != nil {
			return err
		}
	}
	return nil
}

func generatedFilename(source string) string {
	return strings.TrimSuffix(source, ".gox") + "_gox.go"
}

// Appending _gox hides Go's filename constraints, so carry them into the
// generated header instead. Explicit source constraints keep their meaning.
func generatedBuildConstraint(source string, data []byte, operatingSystems, architectures map[string]bool) ([]byte, error) {
	parts := strings.Split(strings.TrimSuffix(filepath.Base(source), ".gox"), "_")
	var platform constraint.Expr
	if len(parts) > 1 && architectures[parts[len(parts)-1]] {
		platform = &constraint.TagExpr{Tag: parts[len(parts)-1]}
		parts = parts[:len(parts)-1]
	}
	if len(parts) > 1 && operatingSystems[parts[len(parts)-1]] {
		os := &constraint.TagExpr{Tag: parts[len(parts)-1]}
		if platform == nil {
			platform = os
		} else {
			platform = &constraint.AndExpr{X: os, Y: platform}
		}
	}
	if platform == nil {
		return data, nil
	}
	var current, legacy constraint.Expr
	var kept []string
	header := true
	for _, line := range strings.Split(string(data), "\n") {
		if strings.HasPrefix(line, "package ") {
			header = false
		}
		if header && (constraint.IsGoBuild(line) || constraint.IsPlusBuild(line)) {
			parsed, err := constraint.Parse(line)
			if err != nil {
				return nil, err
			}
			if constraint.IsGoBuild(line) {
				current = parsed
			} else if legacy == nil {
				legacy = parsed
			} else {
				legacy = &constraint.AndExpr{X: legacy, Y: parsed}
			}
			continue
		}
		kept = append(kept, line)
	}
	if current == nil {
		current = legacy
	}
	if current != nil {
		platform = &constraint.AndExpr{X: platform, Y: current}
	}
	return []byte("//go:build " + platform.String() + "\n\n" + strings.TrimLeft(strings.Join(kept, "\n"), "\n")), nil
}

func generatedGo(name string, data []byte) bool {
	file, err := goparser.ParseFile(gotoken.NewFileSet(), name, data, goparser.PackageClauseOnly|goparser.ParseComments)
	return err == nil && goast.IsGenerated(file)
}

func checkGeneratedOutput(name string) error {
	info, err := os.Lstat(name)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !info.Mode().IsRegular() {
		return fmt.Errorf("refusing to overwrite non-regular generated output %s", name)
	}
	data, err := os.ReadFile(name)
	if err != nil {
		return err
	}
	if !generatedGo(name, data) {
		return fmt.Errorf("refusing to overwrite %s: missing Code generated marker", name)
	}
	return nil
}

var runtimeImport = regexp.MustCompile(`github\.com/goxide-lang/(?:std|serde)(?:/[A-Za-z0-9_]+)*`)

func generationDependencyError(err error) error {
	message := err.Error()
	if !strings.Contains(message, "offline export data for ") {
		return err
	}
	for _, path := range runtimeImport.FindAllString(message, -1) {
		if strings.Contains(message, "cannot find module providing package "+path+":") || strings.Contains(message, "no required module provides package "+path+";") {
			return fmt.Errorf("generated Go needs %s, which is not in this module\nadd it with: go get %s\n\n%w", path, path, err)
		}
	}
	return err
}
