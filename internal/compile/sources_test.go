package compile

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/goxide-lang/goxide/internal/project"
)

func TestStageSourcesRebuildsPublishedFileEntry(t *testing.T) {
	root := t.TempDir()
	const generated = "// Code generated by goxide. DO NOT EDIT.\n\npackage example\n"
	for name, source := range map[string]string{
		"src/lib.gox":              "package example\npub func Value() int { return 42 }\n",
		"lib_gox.go":               generated,
		"orphan_gox.go":            generated,
		"directory_gox.go":         generated,
		"hand.gox":                 "package example\n",
		"hand_gox.go":              "package example\n// A hand-written native file.\n",
		"testdata/template_gox.go": generated,
	} {
		writeProjectFile(t, root, name, source)
	}
	if err := os.Mkdir(filepath.Join(root, "directory.gox"), 0755); err != nil {
		t.Fatal(err)
	}
	library := project.Target{Name: "example", Path: "src/lib.gox"}
	node := &project.Node{Root: root, Module: "example.org/library", Manifest: project.Manifest{Lib: &library}, ModBytes: []byte("module example.org/library\ngo 1.27\n")}
	output := filepath.Join(t.TempDir(), "module")
	if _, _, err := stageSources(node, library, "lib", output, true, nil); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"lib_gox.go", "orphan_gox.go", "directory_gox.go"} {
		if _, err := os.Stat(filepath.Join(output, name)); !os.IsNotExist(err) {
			t.Fatalf("owned output %s was staged as source: %v", name, err)
		}
	}
	for _, name := range []string{"lib.gox", "hand_gox.go", "testdata/template_gox.go"} {
		if _, err := os.Stat(filepath.Join(output, name)); err != nil {
			t.Fatalf("required source %s was discarded: %v", name, err)
		}
	}
}

func TestStageSourcesRetainsPublishedGoOnlyDependency(t *testing.T) {
	root := t.TempDir()
	const generated = "// Code generated by goxide. DO NOT EDIT.\n\npackage example\nfunc Value() int { return 42 }\n"
	writeProjectFile(t, root, "lib_gox.go", generated)
	for _, name := range []string{"testdata/template.gox", "_assets/template.gox", ".assets/template.gox", "_template.gox"} {
		writeProjectFile(t, root, name, "not a package input")
	}
	node := &project.Node{Root: root, Module: "example.org/library", ModBytes: []byte("module example.org/library\ngo 1.27\n")}
	output := filepath.Join(t.TempDir(), "module")
	if _, _, err := stageSources(node, project.Target{Name: "library", Path: "."}, "lib", output, false, nil); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(filepath.Join(output, "lib_gox.go"))
	if err != nil || string(data) != generated {
		t.Fatalf("published Go-only dependency was changed or excluded: %q, %v", data, err)
	}
}
