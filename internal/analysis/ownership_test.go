package analysis_test

import (
	"context"
	"os"
	"path/filepath"
	"testing"

	"github.com/goxide-lang/goxide/internal/analysis"
	"github.com/goxide-lang/goxide/internal/source"
)

func TestFixedInputsExcludeOnlyManagedGeneratedOutputs(t *testing.T) {
	var modules []analysis.Module
	for _, module := range []struct {
		name string
		gox  bool
	}{
		{"app", false},       // The entry remains managed after its last .gox deletion.
		{"published", false}, // Published Go-only dependency output remains input.
		{"dependency", true},
	} {
		dir := t.TempDir()
		for name, text := range map[string]string{
			"old_gox.go":   source.GeneratedHeader + "package p\nconst Old = 1\n",
			"hand_gox.go":  "package p\nconst Hand = 2\n",
			"other_gox.go": "// Code generated by another tool. DO NOT EDIT.\n\npackage p\nconst Other = 3\n",
		} {
			if err := os.WriteFile(filepath.Join(dir, name), []byte(text), 0600); err != nil {
				t.Fatal(err)
			}
		}
		if module.gox {
			if err := os.WriteFile(filepath.Join(dir, "new.gox"), []byte("package p\n"), 0600); err != nil {
				t.Fatal(err)
			}
		}
		modules = append(modules, analysis.Module{Path: "example.test/" + module.name, Dir: dir})
	}
	input, err := analysis.LoadInput(context.Background(), analysis.Input{Modules: modules})
	if err != nil {
		t.Fatal(err)
	}
	for _, module := range modules {
		for _, name := range []string{"hand_gox.go", "other_gox.go"} {
			if input.Files[module.Path+"/"+name] == nil {
				t.Errorf("discarded ordinary input %s/%s", module.Path, name)
			}
		}
		_, exists := input.Files[module.Path+"/old_gox.go"]
		if exists != (module.Path == "example.test/published") {
			t.Errorf("incorrect ownership for %s/old_gox.go: included=%t", module.Path, exists)
		}
	}
}
