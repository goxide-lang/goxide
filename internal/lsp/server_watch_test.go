func TestLanguageServerWatchesGeneratedOutputChanges(t *testing.T) {
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	writeLanguageFile(t, root, "go.mod", "module example.org/watch\n\ngo 1.27\n")
	writeLanguageFile(t, root, "main.gox", "package app\nfunc Main() {}\n")
	w, err := prepareWorkspace(t.Context(), root, compile.Options{Offline: true})
	if err != nil {
		t.Fatal(err)
	}
	defer w.close()
	server := &Server{ctx: t.Context(), initialized: true, epoch: 1, documents: NewDocumentStore(source.UTF16), changed: make(chan struct{}), work: make(chan struct{}, 1), options: ServerOptions{Directory: root, Compiler: compile.Options{TargetDir: "artifacts"}, Log: io.Discard}}
	server.setWorkspaceCallbacks(w)
	writeLanguageFile(t, root, "nested/go.mod", "module example.org/nested\n\ngo 1.27\n")
	for _, test := range []struct {
		name, text string
		kind       int
		want       bool
	}{
		{"orphan_gox.go", source.GeneratedHeader + "package app\nfunc Orphan() {}\n", 1, true},
		{"orphan_gox.go", source.GeneratedHeader + "package app\nfunc Changed() {}\n", 2, true},
		{"manual_gox.go", "package app\nfunc Manual() {}\n", 1, true},
		{"manual_gox.go", source.GeneratedHeader + "package app\nfunc Converted() {}\n", 2, true},
		{"manual_gox.go", "package app\nfunc AuthoredAgain() {}\n", 2, true},
		{"nested/orphan_gox.go", source.GeneratedHeader + "package nested\n", 1, false},
		{"testdata/orphan_gox.go", source.GeneratedHeader + "package app\n", 1, false},
		{".hidden/orphan_gox.go", source.GeneratedHeader + "package app\n", 1, false},
		{"artifacts/orphan_gox.go", source.GeneratedHeader + "package app\n", 1, false},
	} {
		t.Run(test.name, func(t *testing.T) {
			writeLanguageFile(t, root, test.name, test.text)
			uri, _ := PathToURI(filepath.Join(root, test.name))
			params, _ := json.Marshal(map[string]any{"changes": []any{map[string]any{"uri": uri, "type": test.kind}}})
			before := server.epoch
			server.reload = false
			select {
			case <-server.work:
			default:
			}
			if err := server.notification(context.Background(), "workspace/didChangeWatchedFiles", params); err != nil {
				t.Fatal(err)
			}
			if changed := server.epoch != before; changed != test.want || server.reload != test.want || (len(server.work) != 0) != test.want {
				t.Fatalf("watch %s type %d: changed=%t reload=%t queued=%d, want=%t", test.name, test.kind, changed, server.reload, len(server.work), test.want)
			}
		})
	}
}

func TestLanguageServerGeneratedWatchPreservesHeaderOwnership(t *testing.T) {
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	writeLanguageFile(t, root, "go.mod", "module example.org/owned\n\ngo 1.27\n")
	writeLanguageFile(t, root, "main.gox", "package app\nfunc Main() {}\n")
	for name, text := range map[string]string{
		"orphan_gox.go": source.GeneratedHeader + "package app\nfunc Orphan() {}\n",
		"manual_gox.go": "package app\nfunc Manual() {}\n",
		"other_gox.go":  "// Code generated by another tool. DO NOT EDIT.\npackage app\nfunc Other() {}\n",
	} {
		writeLanguageFile(t, root, name, text)
	}
	w, err := prepareWorkspace(t.Context(), root, compile.Options{Offline: true})
	if err != nil {
		t.Fatal(err)
	}
	defer w.close()
	server := &Server{}
	current := &publishedAnalysis{result: &analysis.Result{Sources: map[string]*analysis.Source{}}}
	_, masked, err := server.projectGo(current, w, nil)
	if err != nil {
		t.Fatal(err)
	}
	ownedURI, _ := PathToURI(filepath.Join(root, "orphan_gox.go"))
	if len(masked) != 1 || masked[ownedURI] != "app" {
		t.Fatalf("output watch widened header ownership: %v", masked)
	}
	for _, name := range []string{"manual_gox.go", "other_gox.go"} {
		if !w.ownsSource(filepath.Join(root, name)) {
			t.Fatalf("non-owned output %s no longer participates as authored Go", name)
		}
	}
}
