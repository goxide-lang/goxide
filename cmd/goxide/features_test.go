func TestGenerateFeatureConfigurations(t *testing.T) {
	root := t.TempDir()
	singleFileWrite(t, root, "go.mod", "module example.org/cfggen\n\ngo 1.27\n")
	native := `package main
//go:generate go generate ./child
//go:generate goxide gen %s .
import (
    "fmt"
    "example.org/cfggen/child"
)
func main() { fmt.Println(Encode(), HasJSON, Trace(), child.Enabled()) }
`
	singleFileWrite(t, root, "codec.gox", `package main
#[cfg(feature("json"))]
func Encode() string { return "json" }
#[cfg(not(feature("json")))]
func Encode() string { return "plain" }
const HasJSON = cfg!(feature("json"))
func Trace() bool {
    if cfg!(feature("trace")) { return true } else { return false }
}
`)
	singleFileWrite(t, root, "optional.gox", "package main\n#[cfg(feature(\"json\"))]\nconst Extra = 7\n")
	singleFileWrite(t, root, "main_test.go", `package main
import "testing"
func TestConfiguration(t *testing.T) {
    if (Encode() == "json") != HasJSON { t.Fatal("inconsistent feature configuration") }
}
`)
	singleFileWrite(t, root, "child/generate.go", "package child\n//go:generate goxide gen .\n")
	singleFileWrite(t, root, "child/child.gox", "package child\nfunc Enabled() bool { return cfg!(feature(\"json\")) }\n")
	tool := filepath.Join(runtime.GOROOT(), "bin", "go")
	bin := t.TempDir()
	command := exec.Command(tool, "build", "-o", filepath.Join(bin, "goxide"), ".")
	command.Env = append(os.Environ(), "GOTOOLCHAIN=local", "GOWORK=off")
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("build generator: %v\n%s", err, output)
	}
	goCommand := func(args ...string) string {
		t.Helper()
		cmd := exec.Command(tool, args...)
		cmd.Dir = root
		cmd.Env = append(os.Environ(), "GOTOOLCHAIN=local", "GOWORK=off", "GOPROXY=off", "PATH="+bin+string(os.PathListSeparator)+os.Getenv("PATH"))
		output, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("go %v: %v\n%s", args, err, output)
		}
		return string(output)
	}
	var enabled []byte
	for _, configuration := range []struct{ flag, want string }{
		{"--features=json,trace,json", "json true true false\n"},
		{"", "plain false false false\n"},
		{"--features=trace,json", "json true true false\n"},
	} {
		singleFileWrite(t, root, "main.go", strings.ReplaceAll(native, "%s", configuration.flag))
		before := singleFileSnapshot(t, root)
		goCommand("generate", "./...")
		goCommand("build", "-o", filepath.Join(t.TempDir(), "app"), ".")
		if output := goCommand("run", "."); output != configuration.want {
			t.Fatalf("%s: output = %q, want %q", configuration.flag, output, configuration.want)
		}
		goCommand("test", "./...")
		after := singleFileSnapshot(t, root)
		for name, contents := range before {
			if !strings.HasSuffix(name, "_gox.go") && after[name] != contents {
				t.Fatalf("generation changed %s", name)
			}
		}
		if _, err := os.Stat(filepath.Join(root, "go.sum")); !os.IsNotExist(err) {
			t.Fatalf("generation added go.sum: %v", err)
		}
		generated, err := os.ReadFile(filepath.Join(root, "codec_gox.go"))
		if err != nil {
			t.Fatal(err)
		}
		if configuration.flag == "" {
			file, err := goparser.ParseFile(token.NewFileSet(), filepath.Join(root, "optional_gox.go"), nil, 0)
			if err != nil || len(file.Decls) != 0 {
				t.Fatalf("disabled file must overwrite old declarations with a package shell: %v", err)
			}
		} else if enabled == nil {
			enabled = generated
		} else if !bytes.Equal(enabled, generated) {
			t.Fatal("reordered/deduplicated requests changed generated bytes")
		}
		goCommand("generate", "./...")
		if repeated := singleFileSnapshot(t, root); repeated["codec_gox.go"] != after["codec_gox.go"] || repeated["optional_gox.go"] != after["optional_gox.go"] {
			t.Fatal("repeated configuration changed generated bytes")
		}
	}
	before := singleFileSnapshot(t, root)
	source, err := os.ReadFile(filepath.Join(root, "codec.gox"))
	if err != nil {
		t.Fatal(err)
	}
	singleFileWrite(t, root, "codec.gox", string(source)+"\nfunc Broken() { if cfg!(any()) { missing() } }\n")
	var output bytes.Buffer
	err = run([]string{"gen", "--features=json,trace", root}, &output, &output)
	if err == nil || !strings.Contains(err.Error(), "unresolved name") || !strings.Contains(err.Error(), "codec.gox:11:") {
		t.Fatalf("false if branch was not checked: %v", err)
	}
	after := singleFileSnapshot(t, root)
	for name, contents := range before {
		if strings.HasSuffix(name, "_gox.go") && after[name] != contents {
			t.Fatalf("failed generation changed %s", name)
		}
	}
}

func TestFeatureSingleFileAndPartialGeneration(t *testing.T) {
	root := t.TempDir()
	singleFileWrite(t, root, "go.mod", "module example.org/cfgsingle\n\ngo 1.27\n")
	fixtureRootsFile(t, root, "")
	input := filepath.Join(root, "main.gox")
	singleFileWrite(t, root, "main.gox", `package main
use fmt;
#[cfg(feature("json"))]
func Value() string { return "json" }
#[cfg(not(feature("json")))]
func Value() string { return "plain" }
func main() { fmt::Println(Value(), cfg!(feature("json"))) }
`)
	for _, test := range []struct{ features, want string }{{"json", "json true\n"}, {"", "plain false\n"}} {
		var output bytes.Buffer
		if err := run([]string{"run", "--features=" + test.features, input}, &output, &output); err != nil || output.String() != test.want {
			t.Fatalf("single-file run (%s): %v\n%s", test.features, err, &output)
		}
		output.Reset()
		if err := run([]string{"gen", "--features=" + test.features, "-o", "-", input}, &output, &output); err != nil || !strings.Contains(output.String(), "func Value()") {
			t.Fatalf("single-file stdout (%s): %v\n%s", test.features, err, &output)
		}
	}
	if output, err := projectRun(t, root, "run"); err != nil || output != "plain false\n" {
		t.Fatalf("native directory must retain an open, empty feature set: %v\n%s", err, output)
	}
	for _, args := range [][]string{{"gen", input}, {"gen", "--features=json", input}, {"gen", "--features=", input}} {
		var output bytes.Buffer
		if err := run(args, &output, &output); err == nil || !strings.Contains(err.Error(), "directory input") {
			t.Fatalf("partial generation %v: %v", args, err)
		}
	}
	// A source with no configuration must also not partially replace a package
	// whose other sources have configuration-dependent declarations.
	singleFileWrite(t, root, "plain.gox", "package main\nfunc Plain() int { return 42 }\n")
	var output bytes.Buffer
	if err := run([]string{"gen", filepath.Join(root, "plain.gox")}, &output, &output); err == nil || !strings.Contains(err.Error(), "directory input") {
		t.Fatalf("mixed package configuration accepted: %v", err)
	}
	if err := run([]string{"gen", "--no-default-features", root}, &output, &output); err == nil || !strings.Contains(err.Error(), "requires goxide.toml") {
		t.Fatalf("native defaults accepted: %v", err)
	}
	if err := run([]string{"gen", "--features=bad/name", root}, &output, &output); err == nil || !strings.Contains(err.Error(), "feature") {
		t.Fatalf("invalid feature accepted: %v", err)
	}
}

func TestManifestFeatureCLI(t *testing.T) {
	root := t.TempDir()
	projectWrite(t, root, map[string]string{
		"goxide.toml": `[go_mod]
module = "example.org/cfgcli"
go = "1.27"
[[bin]]
name = "app"
path = "src"
[features]
default = ["json"]
json = []
[dependencies]
fmt = { go = "fmt" }
`,
		"src/main.gox": `package main
use fmt;
#[cfg(feature("json"))]
func Value() string { return "json" }
#[cfg(not(feature("json")))]
func Value() string { return "plain" }
func main() { fmt::Println(Value(), cfg!(feature("json"))) }
`,
		"src/main_test.go": "package main\nimport \"testing\"\nfunc TestValue(t *testing.T) { if Value() != \"json\" && Value() != \"plain\" { t.Fatal(Value()) } }\n",
	})
	for _, test := range []struct {
		flags []string
		want  string
	}{{nil, "json true\n"}, {[]string{"--no-default-features", "--locked"}, "plain false\n"}, {[]string{"--no-default-features", "--features=json,json", "--locked"}, "json true\n"}} {
		args := append([]string{"run", "--offline"}, test.flags...)
		if output, err := projectRun(t, root, args...); err != nil || output != test.want {
			t.Fatalf("manifest %v: %v\n%s", args, err, output)
		}
	}
	for _, args := range [][]string{{"build", "--offline", "--locked"}, {"test", "--offline", "--locked"}, {"transpile", "--bin=app", "--no-default-features", "--offline", "--locked"}} {
		if output, err := projectRun(t, root, args...); err != nil {
			t.Fatalf("manifest %v: %v\n%s", args, err, output)
		}
	}
	if _, err := projectRun(t, root, "run", "--features=missing", "--offline"); err == nil || !strings.Contains(err.Error(), "unknown feature") {
		t.Fatalf("unknown manifest feature accepted: %v", err)
	}
}

func TestFeaturePartialGenerationRejectsMacroConstructedConfiguration(t *testing.T) {
	root := t.TempDir()
	singleFileWrite(t, root, "go.mod", "module example.org/partialcfg\n\ngo 1.27\n")
	singleFileWrite(t, root, "a.gox", `package p
macro_rules! configured {
    ($attribute:ident) => { #[$attribute(feature("on"))] func Hidden() int { return 42 } };
}

configured!(cfg);
func Value() int { return 7 }
`)
	singleFileWrite(t, root, "b.gox", "package p\nfunc Other() int { return Hidden() }\n")
	var output bytes.Buffer
	if err := run([]string{"gen", "--features=on", root}, &output, &output); err != nil {
		t.Fatalf("initial generation: %v\n%s", err, &output)
	}
	before := singleFileSnapshot(t, root)
	for _, name := range []string{"a.gox", "b.gox"} {
		err := run([]string{"gen", filepath.Join(root, name)}, &output, &output)
		if err == nil || !strings.Contains(err.Error(), "whole-package generation") {
			t.Fatalf("partial %s accepted macro-produced configuration: %v", name, err)
		}
		if !reflect.DeepEqual(before, singleFileSnapshot(t, root)) {
			t.Fatal("rejected partial generation changed the package")
		}
	}
}

func TestFeaturePartialGenerationSourceGuard(t *testing.T) {
	for _, test := range []struct {
		name, source string
		want         bool
	}{
		{"ordinary names", "package p\nfunc cfg() bool { cfg_attr := true; return cfg_attr }\n", false},
		{"comments and strings", "package p\n// cfg!(all())\nconst Text = \"#[cfg(all())]\"\n", false},
		{"captured macro name", "package p\nmacro_rules! query { ($name:ident) => { $name!(all()) }; }\nconst Enabled = query!(cfg)\n", true},
		{"nested macro input", "package p\nwrap!((cfg_attr));\n", true},
		{"configuration after invalid sibling syntax", "invalid unselected Goxide\nconfigured!(cfg);\n", true},
		{"invalid unconfigured sibling", "invalid unselected Goxide\n", false},
	} {
		t.Run(test.name, func(t *testing.T) {
			if got := sourceUsesConfiguration([]byte(test.source)); got != test.want {
				t.Fatalf("configuration use = %v, want %v", got, test.want)
			}
		})
	}
}

func TestGenerateNestedNativeModuleKeepsItsBoundary(t *testing.T) {
	root := t.TempDir()
	projectWrite(t, root, map[string]string{
		"goxide.toml":          "[go_mod]\nmodule = \"example.org/outer\"\ngo = \"1.27\"\n[[bin]]\nname = \"app\"\npath = \"src\"\n",
		"src/main.gox":         "package main\nfunc main() {}\n",
		"native/go.mod":        "module example.org/native\n\ngo 1.27\n",
		"native/pkg/value.gox": "package value\nfunc Value() bool { return cfg!(feature(\"local\")) }\n",
	})
	before := singleFileSnapshot(t, root)
	var output bytes.Buffer
	if err := run([]string{"gen", "--features=local", filepath.Join(root, "native/pkg")}, &output, &output); err != nil {
		t.Fatalf("nested native generation: %v\n%s", err, &output)
	}
	generated := filepath.Join(root, "native/pkg/value_gox.go")
	data, err := os.ReadFile(generated)
	if err != nil || !strings.Contains(string(data), "return true") {
		t.Fatalf("nested package was not generated with its configuration: %v\n%s", err, data)
	}
	after := singleFileSnapshot(t, root)
	delete(after, "native/pkg/value_gox.go")
	if !reflect.DeepEqual(before, after) {
		t.Fatal("nested native generation changed its outer manifest project")
	}
}

func TestGenerateSymlinkKeepsNativeModuleBoundary(t *testing.T) {
	outer, native := t.TempDir(), t.TempDir()
	projectWrite(t, outer, map[string]string{
		"goxide.toml":  "[go_mod]\nmodule = \"example.org/outer\"\ngo = \"1.27\"\n[[bin]]\nname = \"app\"\npath = \"src\"\n",
		"src/main.gox": "package main\nfunc main() {}\n",
	})
	singleFileWrite(t, native, "go.mod", "module example.org/native\n\ngo 1.27\n")
	singleFileWrite(t, native, "pkg/value.gox", "package value\nconst Enabled = cfg!(feature(\"local\"))\n")
	before := singleFileSnapshot(t, outer)
	link := filepath.Join(outer, "linked")
	if err := os.Symlink(filepath.Join(native, "pkg"), link); err != nil {
		t.Fatal(err)
	}
	var output bytes.Buffer
	if err := run([]string{"gen", "--features=local", link}, &output, &output); err != nil {
		t.Fatalf("linked native generation: %v\n%s", err, &output)
	}
	if data, err := os.ReadFile(filepath.Join(native, "pkg/value_gox.go")); err != nil || !strings.Contains(string(data), "true") {
		t.Fatalf("linked package was not generated: %v\n%s", err, data)
	}
	if err := os.Remove(link); err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(before, singleFileSnapshot(t, outer)) {
		t.Fatal("linked native generation changed the outer manifest project")
	}
}
