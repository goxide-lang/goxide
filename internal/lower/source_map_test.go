func TestGenerateSourceMaps(t *testing.T) {
	const name = "mapfixture/main.gox"
	text := strings.ReplaceAll(`package fixture
// Unicode π 😀 before reordered output.
pub func value(π int) int { return π }
macro_rules! twice { ($v:expr) => { $v + $v }; }
func duplicate(数 int) int { return twice!(value(数)) }
macro_rules! local { ($v:expr) => { func() int { value := $v; return value }() }; }
macro_rules! relay { ($v:expr) => { local!($v) }; }
func scoped(x int) int { value := 1; return value + relay!(x) }
enum Choice { Number(int), Empty }
func choose(v Choice) int { return match v { Choice::Number(n) => n, Choice::Empty => 0 } }
`, "\n", "\r\n")
	result, err := analysis.Analyze(context.Background(), analysis.Input{PackagePath: "mapfixture", Sources: map[string][]byte{name: []byte(text)}, Options: analysis.Options{PreserveSyntax: true}})
	if err != nil {
		t.Fatal(err)
	}
	for _, directives := range []bool{false, true} {
		maps := map[string]*source.Map{}
		output, err := lower.Generate(context.Background(), result, lower.GenerationOptions{SourceMaps: maps, LineDirectives: directives})
		if err != nil {
			t.Fatal(err)
		}
		plain, err := lower.Generate(context.Background(), result, lower.GenerationOptions{LineDirectives: directives})
		if err != nil || !bytes.Equal(output[name], plain[name]) {
			t.Fatalf("mapping changed generated bytes: %v", err)
		}
		generated, mapping := string(output[name]), maps[name]
		if mapping == nil {
			t.Fatal("missing source map")
		}
		at := strings.Index(generated, "Value")
		entry, ok := mapping.Generated(source.ByteSpan{Start: at, End: at + len("Value")})
		if !ok || entry.Kind != source.Derived || text[entry.Source.Span.Start:entry.Source.Span.End] != "value" {
			t.Fatalf("pub rename mapping: %+v", entry)
		}
		at = strings.Index(generated, "π int")
		entry, ok = mapping.Generated(source.ByteSpan{Start: at, End: at + len("π")})
		if !ok || entry.Kind != source.Exact || entry.Source.File != name || text[entry.Source.Span.Start:entry.Source.Span.End] != "π" {
			t.Fatalf("Unicode identifier mapping: %+v", entry)
		}
		capture := strings.Index(text, "value(数)") + len("value(")
		occurrences := mapping.Original(source.Location{File: name, Span: source.ByteSpan{Start: capture, End: capture + len("数")}})
		if len(occurrences) != 2 {
			t.Fatalf("macro capture reverse occurrences = %+v\n%s", occurrences, generated)
		}
		for _, occurrence := range occurrences {
			if generated[occurrence.Generated.Start:occurrence.Generated.End] != "数" || len(occurrence.Expansions) == 0 {
				t.Fatalf("capture provenance: %+v", occurrence)
			}
			for _, expansion := range occurrence.Expansions {
				if expansion.Definition.File != name || expansion.Call.File != name || expansion.Definition.Span.End <= expansion.Definition.Span.Start || expansion.Call.Span.End <= expansion.Call.Span.Start {
					t.Fatalf("macro trace: %+v", expansion)
				}
			}
		}
		nested := strings.Index(text, "relay!(x)") + len("relay!(")
		nestedOccurrences := mapping.Original(source.Location{File: name, Span: source.ByteSpan{Start: nested, End: nested + 1}})
		if len(nestedOccurrences) != 1 || len(nestedOccurrences[0].Expansions) != 2 {
			t.Fatalf("nested expansion trace: %+v", nestedOccurrences)
		}
		hygiene := false
		for _, entry := range mapping.Entries() {
			if entry.Kind == source.Derived && len(entry.Expansions) == 2 && entry.Source.Span.End-entry.Source.Span.Start == len("value") && text[entry.Source.Span.Start:entry.Source.Span.End] == "value" {
				hygiene = generated[entry.Generated.Start:entry.Generated.End] != "value"
				if hygiene {
					break
				}
			}
		}
		if !hygiene {
			t.Fatal("hygienic renamed identifier lacks derived provenance")
		}
		temporary := regexp.MustCompile(`gxMatch[0-9]+`).FindStringIndex(generated)
		if temporary == nil {
			t.Fatalf("fixture has no generated temporary:\n%s", generated)
		}
		entry, ok = mapping.Generated(source.ByteSpan{Start: temporary[0], End: temporary[1]})
		if !ok || entry.Kind != source.Synthetic || entry.Source.File != "" {
			t.Fatalf("synthetic temporary has a navigable source: %+v", entry)
		}
	}
}

func TestGenericValidationExplicitSource(t *testing.T) {
	for _, body := range []string{`_ = value["text"]`, `bad!(value)`} {
		text := `package p
macro_rules! bad { ($v:expr) => { _ = $v["text"] }; }
func unused[const N int](value [N]int) { ` + body + ` }
`
		_, err := lowerDeriveSources(map[string]string{"generic.gox": text})
		var diagnostic *analysis.Diagnostic
		if !errors.As(err, &diagnostic) || !strings.Contains(diagnostic.Message, "泛型定义检查失败") {
			t.Fatalf("missing validation diagnostic: %v", err)
		}
		if diagnostic.File != "generic.gox" || diagnostic.Span.Start == 0 || text[diagnostic.Span.Start:diagnostic.Span.End] != `"text"` {
			t.Fatalf("error attributed to wrong source: %+v", diagnostic)
		}
		if strings.HasPrefix(body, "bad!") && (diagnostic.Call.File == nil || diagnostic.Definition.File == nil || len(diagnostic.Origin.Stack) == 0) {
			t.Fatalf("missing validation macro provenance: %+v", diagnostic)
		}
	}
}

func TestSourceMapAfterImportAndTargetRewriting(t *testing.T) {
	const name = "mapfixture/main.gox"
	text := "package main\n// zed documentation\nuse mapfixture::zed;\n// alpha documentation\nuse mapfixture::alpha;\nconst Target = cfg!(target_os(\"linux\"))\nfunc main() { println(zed::Value()+alpha::Value()) }\n"
	inputs := map[string][]byte{
		name:                       []byte(text),
		"mapfixture/zed/lib.gox":   []byte("package zed\npub func Value() int {return 1}\n"),
		"mapfixture/alpha/lib.gox": []byte("package alpha\npub func Value() int {return 2}\n"),
	}
	result, err := analysis.Analyze(context.Background(), analysis.Input{Files: inputs, Modules: []analysis.Module{{Path: "mapfixture", Dir: t.TempDir(), Config: targetConfig(t, "linux/386")}}, Options: analysis.Options{PreserveSyntax: true}})
	if err != nil {
		t.Fatal(err)
	}
	maps := map[string]*source.Map{}
	output, err := lower.Generate(context.Background(), result, lower.GenerationOptions{SourceMaps: maps})
	if err != nil {
		t.Fatal(err)
	}
	generated := string(output[name])
	if !strings.HasPrefix(generated, "//go:build linux && !android && 386\n") || strings.Index(generated, `"mapfixture/alpha"`) > strings.Index(generated, `"mapfixture/zed"`) {
		t.Fatalf("fixture did not rewrite target/imports:\n%s", generated)
	}
	at := strings.Index(generated, "zed.Value")
	entry, ok := maps[name].Generated(source.ByteSpan{Start: at, End: at + 3})
	want := strings.Index(text, "zed::Value")
	if !ok || entry.Kind != source.Exact || entry.Source != (source.Location{File: name, Span: source.ByteSpan{Start: want, End: want + 3}}) {
		t.Fatalf("post-rewrite reference mapping: %+v", entry)
	}
}
