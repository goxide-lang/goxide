package compile

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"reflect"
	"testing"

	"github.com/goxide-lang/goxide/internal/project"
)

func TestLocalPublishedDependencyTransport(t *testing.T) {
	for _, source := range []string{"path", "git"} {
		t.Run(source, func(t *testing.T) {
			base, err := filepath.EvalSymlinks(t.TempDir())
			if err != nil {
				t.Fatal(err)
			}
			library, app := filepath.Join(base, "library"), filepath.Join(base, "app")
			files := map[string]string{
				project.ManifestName: "[go_mod]\nmodule='example.org/local-transport/library'\ngo='1.27'\n[lib]\nname='library'\npath='.'\n",
				"go.mod":             "module example.org/local-transport/library\n\ngo 1.27\n",
				"library.gox":        "package library\nfunc Answer() int { return 42 }\n",
			}
			for name, contents := range files {
				writeProjectFile(t, library, name, contents)
			}
			dependency := `path = "../library"`
			if source == "git" {
				for _, args := range [][]string{{"init", "-q"}, {"add", "."}, {"-c", "user.name=Fixture", "-c", "user.email=fixture@example.org", "commit", "-qm", "fixture"}, {"tag", "v1.0.0"}} {
					command := exec.Command("git", append([]string{"-c", "core.hooksPath=/dev/null"}, args...)...)
					command.Dir = library
					command.Env = append(os.Environ(), "GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1")
					if output, err := command.CombinedOutput(); err != nil {
						t.Fatalf("git fixture: %v\n%s", err, output)
					}
				}
				dependency = fmt.Sprintf("git = %q\ntag = 'v1.0.0'", library)
			}
			writeProjectFile(t, app, project.ManifestName, `[go_mod]
module = "example.org/local-transport/app"
go = "1.27"
[[bin]]
name = "app"
path = "src"
[dependencies.library]
`+dependency+"\n")
			writeProjectFile(t, app, "src/main.gox", "package main\nuse library;\nuse fmt;\nfunc main() { fmt::Println(library::Answer()) }\n")
			first, err := PrepareProject(app, Options{})
			if err != nil {
				t.Fatal(err)
			}
			featureGo(t, first.Root, "build", "-o", filepath.Join(base, "program"), first.Entry)
			if got := featureGo(t, first.Root, "run", first.Entry); got != "42\n" {
				t.Fatalf("published dependency output = %q", got)
			}
			generated := projectSnapshot(t, filepath.Dir(first.Root))
			lock, err := os.ReadFile(filepath.Join(app, "goxide.lock"))
			if err != nil {
				t.Fatal(err)
			}
			second, err := PrepareProject(app, Options{Offline: true, Locked: true})
			if err != nil {
				t.Fatal(err)
			}
			after, err := os.ReadFile(filepath.Join(app, "goxide.lock"))
			if err != nil || !bytes.Equal(lock, after) || first.Root != second.Root || !reflect.DeepEqual(generated, projectSnapshot(t, filepath.Dir(second.Root))) {
				t.Fatalf("locked replay changed generated bytes or lock: %v", err)
			}
			for name, want := range files {
				got, err := os.ReadFile(filepath.Join(library, name))
				if err != nil || string(got) != want {
					t.Fatalf("dependency source %s changed: %v", name, err)
				}
			}
		})
	}
}
