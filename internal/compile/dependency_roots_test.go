package compile

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"reflect"
	"runtime"
	"strings"
	"testing"

	"github.com/hxsf/goxide/internal/project"
)

func TestDependencySourcesSelectTheirLibraryRoots(t *testing.T) {
	base := t.TempDir()
	kit := filepath.Join(base, "kit")
	writeProjectFile(t, kit, project.ManifestName, `[go_mod]
module = "example.org/kit"
go = "1.27"
[lib]
name = "kit"
path = "src"
`)
	writeProjectFile(t, kit, "src/lib.gox", "package kit\npub mod value;\n")
	writeProjectFile(t, kit, "src/value/value.gox", "package value\nfunc Answer() int { return 20 }\n")
	native := filepath.Join(base, "native")
	writeProjectFile(t, native, "go.mod", "module example.org/native\ngo 1.27\n")
	writeProjectFile(t, native, "native.go", "package native\nfunc Answer() int { return 12 }\n")
	repo := filepath.Join(base, "repo")
	writeProjectFile(t, repo, "packages/codec/goxide.toml", `[go_mod]
module = "example.org/codec"
go = "1.27"
[lib]
name = "codec"
path = "src/lib.gox"
`)
	writeProjectFile(t, repo, "packages/codec/src/lib.gox", "package codec\nfunc Answer() int { return 10 }\n")
	for _, args := range [][]string{{"init", "-q"}, {"add", "."}, {"-c", "user.name=Fixture", "-c", "user.email=fixture@example.org", "commit", "-qm", "fixture"}, {"tag", "v1.0.0"}} {
		command := exec.Command("git", args...)
		command.Dir = repo
		command.Env = append(os.Environ(), "GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1")
		if output, err := command.CombinedOutput(); err != nil {
			t.Fatalf("git fixture: %v\n%s", err, output)
		}
	}
	app := filepath.Join(base, "app")
	writeProjectFile(t, app, project.ManifestName, fmt.Sprintf(`[go_mod]
module = "example.org/app"
go = "1.27"
[[bin]]
name = "app"
path = "src"
[dependencies]
kit = { path = "../kit" }
native = { path = "../native" }
wire = { git = %q, subdir = "packages/codec", tag = "v1.0.0" }
fmt = { go = "fmt" }
testing = { go = "testing" }
`, repo))
	writeProjectFile(t, app, "src/main.gox", `package main
use kit::value;
use native;
use wire;
use fmt;
func answer() int { return value::Answer() + native::Answer() + wire::Answer() }
func main() { fmt::Println(answer()) }
`)
	writeProjectFile(t, app, "src/main_test.gox", `package main
use testing;
func TestAnswer(t *testing::T) {
    if answer() != 42 { t.Fatal("wrong dependency roots") }
}
`)
	first, err := PrepareProject(app, Options{})
	if err != nil {
		t.Fatal(err)
	}
	command := exec.Command(filepath.Join(runtime.GOROOT(), "bin", "go"), "run", "-mod=readonly", first.Entry)
	command.Dir, command.Env = first.Root, project.GoEnv(true)
	if output, err := command.CombinedOutput(); err != nil || strings.TrimSpace(string(output)) != "42" {
		t.Fatalf("inferred dependency roots: %v\n%s", err, output)
	}
	command = exec.Command(filepath.Join(runtime.GOROOT(), "bin", "go"), "test", "-mod=readonly", "-count=1", first.Entry)
	command.Dir, command.Env = first.Root, project.GoEnv(true)
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("generated dependency root test: %v\n%s", err, output)
	}
	files := projectSnapshot(t, filepath.Dir(first.Root))
	lock, err := os.ReadFile(filepath.Join(app, "goxide.lock"))
	if err != nil {
		t.Fatal(err)
	}
	second, err := PrepareProject(app, Options{Offline: true, Locked: true})
	if err != nil {
		t.Fatal(err)
	}
	after, err := os.ReadFile(filepath.Join(app, "goxide.lock"))
	if err != nil || string(lock) != string(after) || first.Root != second.Root || !reflect.DeepEqual(files, projectSnapshot(t, filepath.Dir(second.Root))) {
		t.Fatalf("locked source replay changed generated bytes or lock: %v", err)
	}
}
