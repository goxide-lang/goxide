package source

import (
	"bytes"
	"strings"
)

const GeneratedHeader = "// Code generated by goxide. DO NOT EDIT.\n\n"

// IsGenerated recognizes an owned output inside a caller-selected source
// scope, even after its .gox input has been removed. It does not classify an
// entire module: published Go-only dependencies remain ordinary Go inputs.
func IsGenerated(name string, data []byte) bool {
	return strings.HasSuffix(name, "_gox.go") && bytes.HasPrefix(data, []byte(GeneratedHeader))
}
