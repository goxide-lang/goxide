func TestProjectFeaturesBuildRunTestAndStableLock(t *testing.T) {
	root := featureProject(t, map[string]string{
		"app/goxide.toml": `[go_mod]
module = "example.org/features/app"
go = "1.27"
[namespaces]
sub = "example.org/features/app/sub"
[[bin]]
name = "app"
path = "cmd/app"
[dependencies]
fmt = { go = "fmt" }
left = { path = "../left" }
right = { path = "../right" }
[features]
default = ["shared"]
shared = []
extra = []
`,
		"app/cmd/app/main.gox": `package main
use fmt;
use sub;
use left;
use right;
const RootDefault = cfg!(feature("default"))
const RootShared = cfg!(feature("shared"))
func main() { fmt::Println(RootDefault, RootShared, sub::Shared(), left::Shared(), left::Value(), right::Value()) }
`,
		"app/sub/value.gox": "package sub\nfunc Shared() bool { return cfg!(feature(\"shared\")) }\n",
		"app/cmd/app/main_test.go": `package main
import (
    "testing"
    "example.org/features/app/sub"
    "example.org/features/left"
    "example.org/features/right"
)
func TestFeatures(t *testing.T) {
    if sub.Shared() != RootShared || left.Shared() || left.Value() != "union" || right.Value() != "union" { t.Fatal("incorrect module feature scope or union") }
}
`,
		"left/goxide.toml": `[go_mod]
module = "example.org/features/left"
go = "1.27"
[lib]
name = "left"
path = "."
[dependencies]
base = { module = "example.org/features/base", path = "../base", default_features = false, features = ["left"] }
`,
		"right/goxide.toml": `[go_mod]
module = "example.org/features/right"
go = "1.27"
[lib]
name = "right"
path = "."
[dependencies]
base = { module = "example.org/features/base", path = "../base", features = ["right"] }
`,
		"left/value.gox":  "package left\nuse base;\nfunc Value()string{return base::Value()}\nfunc Shared()bool{return base::Shared}\n",
		"right/value.gox": "package right\nuse base;\nfunc Value()string{return base::Value()}\n",
		"base/goxide.toml": `[go_mod]
module = "example.org/features/base"
go = "1.27"
[lib]
name = "base"
path = "."
required_features = ["left", "right", "base_default"]
[features]
default = ["base_default"]
base_default = []
left = []
right = []
shared = []
`,
		"base/value.gox": `package base
const Left = cfg!(feature("left"))
const Right = cfg!(feature("right"))
const BaseDefault = cfg!(feature("base_default"))
const Shared = cfg!(feature("shared"))
func Value()string {
    if Left && Right && BaseDefault { return "union" }
    return "missing"
}
`,
		"base/value_test.go": `package base
import "testing"
func TestUnion(t *testing.T) {
    if !Left || !Right || !BaseDefault || Shared { t.Fatal("diamond requests did not merge independently of root features") }
}
`,
	})
	before := projectSnapshot(t, root)
	app := filepath.Join(root, "app")
	var lock []byte
	type generated struct {
		root  string
		files map[string][]byte
	}
	seen := map[string]generated{}
	for _, test := range []struct {
		name, configuration, want string
		features                  []string
		noDefault                 bool
	}{
		{"defaults", "default", "true true true false union union\n", nil, false},
		{"without defaults", "empty", "false false false false union union\n", nil, true},
		{"defaults again", "default", "true true true false union union\n", nil, false},
		{"explicit default survives no-default", "default", "true true true false union union\n", []string{"default"}, true},
		{"explicit after no-default", "explicit", "false true true false union union\n", []string{"shared", "extra", "shared"}, true},
		{"same set reordered", "explicit", "false true true false union union\n", []string{"extra", "shared"}, true},
	} {
		t.Run(test.name, func(t *testing.T) {
			result, err := PrepareProject(app, Options{Offline: true, Locked: lock != nil, Features: test.features, NoDefaultFeatures: test.noDefault})
			if err != nil {
				t.Fatal(err)
			}
			featureGo(t, result.Root, "build", "./...")
			if got := featureGo(t, result.Root, "run", result.Entry); got != test.want {
				t.Fatalf("run = %q, want %q", got, test.want)
			}
			featureGo(t, result.Root, "test", "-count=1", "./...", "example.org/features/base/...")
			files := projectSnapshot(t, filepath.Dir(result.Root))
			if prior, ok := seen[test.configuration]; ok {
				if result.Root != prior.root || !reflect.DeepEqual(files, prior.files) {
					t.Fatal("same feature set changed the artifact path or generated bytes")
				}
			} else {
				for _, prior := range seen {
					if result.Root == prior.root {
						t.Fatal("different feature sets reused the same artifact path")
					}
				}
				seen[test.configuration] = generated{result.Root, files}
			}
			current, err := os.ReadFile(filepath.Join(app, "goxide.lock"))
			if err != nil {
				t.Fatal(err)
			}
			if lock == nil {
				lock = current
			} else if !bytes.Equal(lock, current) {
				t.Fatal("cfg-only feature change modified the dependency lock")
			}
		})
	}
	after := projectSnapshot(t, root)
	for name, contents := range before {
		if !bytes.Equal(contents, after[name]) {
			t.Fatalf("generation modified author source %s", name)
		}
	}
}

func TestProjectOptionalFeaturesAndRequiredLibrary(t *testing.T) {
	root := featureProject(t, map[string]string{
		"app/goxide.toml": `[go_mod]
module = "example.org/optional/app"
go = "1.27"
[[bin]]
name = "app"
path = "."
[dependencies]
fmt = { go = "fmt" }
optional = { module = "example.org/optional/lib", path = "../optional", optional = true, default_features = false }
[features]
network = ["dep:optional", "optional/wire"]
only_dep = ["dep:optional"]
bad_forward = ["optional/unknown"]
`,
		"app/main.gox": `package main
use fmt;
#[cfg(feature("network"))]
use optional;
#[cfg(feature("network"))]
func value() string { return optional::Value() }
#[cfg(not(feature("network")))]
func value() string { return "off" }
func main() { fmt::Println(value()) }
`,
	})
	app := filepath.Join(root, "app")
	off, err := PrepareProject(app, Options{Offline: true})
	if err != nil {
		t.Fatalf("inactive optional source must not be read: %v", err)
	}
	if got := featureGo(t, off.Root, "run", off.Entry); got != "off\n" {
		t.Fatalf("inactive optional run = %q", got)
	}
	lockPath := filepath.Join(app, "goxide.lock")
	lock, err := os.ReadFile(lockPath)
	if err != nil {
		t.Fatal(err)
	}
	before := projectSnapshot(t, filepath.Dir(off.Root))
	writeProjectFile(t, root, "optional/goxide.toml", `[go_mod]
module = "example.org/optional/lib"
go = "1.27"
[lib]
name = "optional"
path = "."
required_features = ["wire"]
[features]
wire = []
`)
	writeProjectFile(t, root, "optional/value.gox", "package optional\n#[cfg(feature(\"wire\"))]\nfunc Value()string{return \"on\"}\n")
	for _, test := range []struct {
		feature, want string
		locked        bool
	}{
		{"network", "locked", true},
		{"only_dep", "requires feature wire", false},
		{"bad_forward", "unknown feature", false},
	} {
		if _, err := PrepareProject(app, Options{Offline: true, Locked: test.locked, Features: []string{test.feature}}); err == nil || !strings.Contains(err.Error(), test.want) {
			t.Fatalf("feature %s: want %q, got %v", test.feature, test.want, err)
		}
		current, err := os.ReadFile(lockPath)
		if err != nil || !bytes.Equal(lock, current) || !reflect.DeepEqual(before, projectSnapshot(t, filepath.Dir(off.Root))) {
			t.Fatalf("rejected configuration changed prior lock or generated module: %v", err)
		}
	}
	on, err := PrepareProject(app, Options{Offline: true, Features: []string{"network"}})
	if err != nil {
		t.Fatal(err)
	}
	featureGo(t, on.Root, "build", "-o", filepath.Join(t.TempDir(), "optional-app"), "./...")
	if got := featureGo(t, on.Root, "run", on.Entry); got != "on\n" {
		t.Fatalf("active optional run = %q", got)
	}
	featureGo(t, on.Root, "test", "-count=1", "./...", "example.org/optional/lib/...")
	current, err := os.ReadFile(lockPath)
	if err != nil || bytes.Equal(lock, current) {
		t.Fatalf("activated optional dependency did not enter lock: %v", err)
	}
	if _, err := PrepareProject(app, Options{Offline: true, Locked: true, Features: []string{"network", "network"}}); err != nil {
		t.Fatalf("locked optional replay: %v", err)
	}
}

func TestProjectRequiredBinaryUsesResolvedFeatures(t *testing.T) {
	root := smallProject(t)
	writeProjectFile(t, root, project.ManifestName, `[go_mod]
module = "example.org/small"
go = "1.27"
[[bin]]
name = "app"
path = "app.gox"
required_features = ["ready"]
[dependencies]
fmt = { go = "fmt" }
[features]
default = ["ready"]
ready = []
`)
	for _, test := range []struct {
		options Options
		want    string
	}{
		{Options{Offline: true, NoDefaultFeatures: true}, "target app requires feature ready"},
		{Options{Offline: true, Features: []string{"unknown"}}, `unknown feature "unknown"`},
	} {
		if _, err := PrepareProject(root, test.options); err == nil || !strings.Contains(err.Error(), test.want) {
			t.Fatalf("unsatisfied feature request was accepted: %v", err)
		}
		if _, err := os.Stat(filepath.Join(root, "goxide.lock")); !os.IsNotExist(err) {
			t.Fatalf("failed feature selection published a lock: %v", err)
		}
	}
	for _, options := range []Options{{Offline: true}, {Offline: true, Locked: true, NoDefaultFeatures: true, Features: []string{"ready"}}} {
		result, err := PrepareProject(root, options)
		if err != nil {
			t.Fatal(err)
		}
		if got := featureGo(t, result.Root, "run", result.Entry); got != "file target\n" {
			t.Fatalf("qualified binary run = %q", got)
		}
	}
}

func TestProjectEmptyFeaturesRemainClosedAndNativeRootIsOpen(t *testing.T) {
	root := smallProject(t)
	writeProjectFile(t, root, "app.gox", "package main\nuse fmt;\nfunc main(){fmt::Println(cfg!(feature(\"unlisted\")))}\n")
	if _, err := PrepareProject(root, Options{Offline: true}); err == nil || !strings.Contains(err.Error(), `unknown feature "unlisted"`) {
		t.Fatalf("empty manifest feature declarations became open: %v", err)
	}
	if _, err := os.Stat(filepath.Join(root, "goxide.lock")); !os.IsNotExist(err) {
		t.Fatalf("invalid cfg query published a lock: %v", err)
	}
	result, err := PrepareProject(root, Options{Offline: true, NativeFeatures: &config.Features{}})
	if err != nil {
		t.Fatal(err)
	}
	if got := featureGo(t, result.Root, "run", result.Entry); got != "false\n" {
		t.Fatalf("native empty feature set = %q", got)
	}
}

func TestProjectPlainGoDependencyRejectsFeatureRequests(t *testing.T) {
	root := featureProject(t, map[string]string{
		"app/goxide.toml": `[go_mod]
module = "example.org/plain/app"
go = "1.27"
[[bin]]
name = "app"
path = "."
[dependencies]
native = { module = "example.org/plain/native", path = "../native", features = ["enhanced"] }
`,
		"app/main.gox":    "package main\nfunc main(){}\n",
		"native/go.mod":   "module example.org/plain/native\n\ngo 1.27\n",
		"native/value.go": "package native\nfunc Value()int{return 42}\n",
	})
	app := filepath.Join(root, "app")
	if _, err := PrepareProject(app, Options{Offline: true}); err == nil || !strings.Contains(err.Error(), "example.org/plain/native") || !strings.Contains(err.Error(), `unknown feature "enhanced"`) {
		t.Fatalf("fixed Go dependency accepted a feature request: %v", err)
	}
	if _, err := os.Stat(filepath.Join(app, "goxide.lock")); !os.IsNotExist(err) {
		t.Fatalf("rejected dependency request published a lock: %v", err)
	}
}

func featureProject(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, contents := range files {
		writeProjectFile(t, root, name, contents)
	}
	return root
}

func featureGo(t *testing.T, root string, args ...string) string {
	t.Helper()
	command := exec.Command(filepath.Join(runtime.GOROOT(), "bin", "go"), args...)
	command.Dir = root
	command.Env = append(project.GoEnv(true), "GOFLAGS=-mod=readonly")
	output, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("go %s: %v\n%s", strings.Join(args, " "), err, output)
	}
	return string(output)
}
