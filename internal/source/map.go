package source

import "sort"

// ByteSpan is a half-open byte range, independent of protocol encoding.
type ByteSpan struct{ Start, End int }

type Location struct {
	File string
	Span ByteSpan
}

type MappingKind uint8

const (
	Synthetic MappingKind = iota // generated text without a source counterpart
	Derived                      // a source construct lowered into different text
	Exact                        // the source and generated bytes are identical
)

type Expansion struct {
	ID               uint32
	Definition, Call Location
}

type Mapping struct {
	Generated  ByteSpan
	Source     Location
	Kind       MappingKind
	Expansions []Expansion // outermost call first
}

// Map owns a fixed set of mappings for one final generated file. Entries can
// overlap because a mapped expression contains more precise mapped tokens.
type Map struct{ entries []Mapping }

func NewMap(entries []Mapping) *Map {
	m := &Map{entries: make([]Mapping, len(entries))}
	for i, entry := range entries {
		m.entries[i] = cloneMapping(entry)
	}
	sort.SliceStable(m.entries, func(i, j int) bool {
		a, b := m.entries[i].Generated, m.entries[j].Generated
		if a.Start != b.Start {
			return a.Start < b.Start
		}
		return a.End < b.End
	})
	return m
}

func cloneMapping(entry Mapping) Mapping {
	entry.Expansions = append([]Expansion(nil), entry.Expansions...)
	return entry
}

func (m *Map) Entries() []Mapping {
	if m == nil {
		return nil
	}
	entries := make([]Mapping, len(m.entries))
	for i, entry := range m.entries {
		entries[i] = cloneMapping(entry)
	}
	return entries
}

func contains(outer, inner ByteSpan) bool {
	return inner.Start >= outer.Start && inner.End >= inner.Start && inner.End <= outer.End && (inner.Start < outer.End || outer.Start == outer.End)
}

// Generated returns the narrowest entry containing the entire requested span.
// Exact ranges are translated byte-for-byte; derived ranges retain their whole
// source construct. Synthetic entries deliberately have no source location.
func (m *Map) Generated(span ByteSpan) (Mapping, bool) {
	if m == nil {
		return Mapping{}, false
	}
	var best Mapping
	found := false
	for _, entry := range m.entries {
		if entry.Generated.Start > span.Start {
			break
		}
		if !contains(entry.Generated, span) {
			continue
		}
		width := entry.Generated.End - entry.Generated.Start
		bestWidth := best.Generated.End - best.Generated.Start
		if !found || width < bestWidth || width == bestWidth && entry.Kind > best.Kind {
			best, found = entry, true
		}
	}
	if found && best.Kind == Exact {
		start := best.Source.Span.Start + span.Start - best.Generated.Start
		best.Source.Span = ByteSpan{start, start + span.End - span.Start}
		best.Generated = span
	}
	return cloneMapping(best), found
}

// Original returns every exact generated occurrence of the requested source
// range. It never snaps to a nearby token or returns a derived replacement.
func (m *Map) Original(location Location) []Mapping {
	if m == nil {
		return nil
	}
	var result []Mapping
	for _, entry := range m.entries {
		if entry.Kind != Exact || entry.Source.File != location.File || !contains(entry.Source.Span, location.Span) {
			continue
		}
		start := entry.Generated.Start + location.Span.Start - entry.Source.Span.Start
		entry.Generated = ByteSpan{start, start + location.Span.End - location.Span.Start}
		entry.Source = location
		result = append(result, cloneMapping(entry))
	}
	return result
}
